def build() -> dict:
    """校验一致性并输出注入用的 JSON。

    台账里的每一个中文单元格值都必须有英文对照 ——
    缺一条就构建失败，而不是让英文界面悄悄留着中文。
    """
    from ur_values_en import VAL_EN, coverage

    vals = {str(c) for m in MODULES for r in m["rows"] for c in r}
    missing = coverage(vals)
    assert not missing, "缺少英文对照的单元格值: " + ", ".join(sorted(missing)[:20])

    # 把单元格值变成双语对象
    for m in MODULES:
        m["rows"] = [[{"zh": str(c), "en": VAL_EN.get(str(c), str(c))} for c in row]
                      for row in m["rows"]]

    ids = [m["id"] for m in MODULES]
    assert len(ids) == len(set(ids)), "子模块 id 重复"
    gids = {g["id"] for g in GROUPS}
    for m in MODULES:
        assert m["g"] in gids, f"{m['id']} 的组 {m['g']} 不存在"
        for c in m["cols"]:
            assert len(c) == 3, f"{m['id']} 列定义不是三元组"
        for r in m["rows"]:
            assert len(r) == len(m["cols"]), f"{m['id']} 记录列数与表头不一致"
        for k in ("zh", "en"):
            assert m["n"][k] and m["p"][k], f"{m['id']} 缺少 {k}"
    counts = {}
    for m in MODULES:
        counts[m["g"]] = counts.get(m["g"], 0) + 1
    for g in GROUPS:
        assert g["id"] in counts, f"组 {g['id']} 没有子模块"
    return {
        "groups": GROUPS,
        "modules": MODULES,
        "counts": counts,
        "total": len(MODULES),
        "evidence": sum(m["ev"] for m in MODULES),
    }


